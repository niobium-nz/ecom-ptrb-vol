export function parseEnvFile(text) {
  const values = {};
  for (const rawLine of String(text).split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const normalized = line.startsWith("export ") ? line.slice(7).trim() : line;
    const separator = normalized.indexOf("=");
    if (separator <= 0) throw new Error(`Invalid environment line: ${rawLine}`);
    const key = normalized.slice(0, separator).trim();
    if (!/^[A-Z][A-Z0-9_]*$/.test(key)) throw new Error(`Invalid environment key: ${key}`);
    let value = normalized.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

async function readEnvFile(filePath) {
  try {
    return parseEnvFile(await readFile(filePath, "utf8"));
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return {};
    throw error;
  }
}

export async function resolvePublicEnvironment({ cwd = process.cwd(), environment = process.env } = {}) {
  const fileValues = {};
  for (const fileName of [".env", ".env.local", ".env.generated"]) {
    Object.assign(fileValues, await readEnvFile(resolve(cwd, fileName)));
  }

  const resolved = {};
  for (const [key, fallback] of Object.entries(PUBLIC_ENV_DEFAULTS)) {
    const value = environment[key] ?? fileValues[key] ?? fallback;
    if (typeof value !== "string" || !value.trim()) throw new Error(`${key} must be a non-empty string`);
    resolved[key] = value.trim();
  }

  if (!/^[1-9]\d*$/.test(resolved.SHIPPING_OPTION_ID)) {
    throw new Error("SHIPPING_OPTION_ID must contain a positive integer in decimal form");
  }
  const shippingOptionId = Number(resolved.SHIPPING_OPTION_ID);
  if (!Number.isSafeInteger(shippingOptionId)) {
    throw new Error("SHIPPING_OPTION_ID must be a safe positive integer");
  }

  return resolved;
}

export function renderPublicEnvironmentModule(values) {
  const serialized = Object.entries(values)
    .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
    .join("\n");
  return `// Generated by scripts/generate-public-env.mjs. This file contains browser-safe values only.\nexport const rawPublicEnv = {\n${serialized}\n} as const;\n`;
}

export async function generatePublicEnvironment({ cwd = process.cwd(), environment = process.env } = {}) {
  const values = await resolvePublicEnvironment({ cwd, environment });
  const outputPath = resolve(cwd, "lib/generated/public-env.ts");
  const temporaryPath = `${outputPath}.tmp`;
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(temporaryPath, renderPublicEnvironmentModule(values), "utf8");
  await rename(temporaryPath, outputPath);
  return { outputPath, keys: Object.keys(values) };
}

export function formatPublicEnvironmentResult(result) {
  return `Generated browser-safe public environment with ${result.keys.length} values.\n`;
}

void runCli({
  direct: isDirectExecution(import.meta.url, process.argv[1]),
  task: generatePublicEnvironment,
  format: formatPublicEnvironmentResult,
});
